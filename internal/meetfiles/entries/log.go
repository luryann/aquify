package entries

import (
	"fmt"
	"strings"
)

const logRule = 40

// logLine pads "Label:" to an 18-column gutter; longer labels get one space.
func logLine(label, value string) string {
	label += ":"
	if len(label) < 18 {
		label += strings.Repeat(" ", 18-len(label))
	} else {
		label += " "
	}
	return label + value
}

func (p *prepared) individualEntryCount() int {
	n := 0
	for _, ev := range p.byEvent {
		n += len(ev.entries)
	}
	return n
}

// entryLog renders the plain-text log that travels with the entry files.
// Lines end in LF and the last line has no terminator.
func (p *prepared) entryLog(fileNames []string) []byte {
	in := p.in
	var address []string
	for _, part := range []string{in.Club.Address1, in.Club.Address2, in.Club.City, in.Club.State, in.Club.PostalCode} {
		if part = strings.TrimSpace(part); part != "" {
			address = append(address, part)
		}
	}
	lsc, code := strings.ToUpper(strings.TrimSpace(in.Club.LSC)), strings.ToUpper(strings.TrimSpace(in.Club.Code))
	lines := []string{
		"ENTRY FILE LOG",
		strings.Repeat("=", logRule),
		logLine("Date", in.GeneratedAt.Format("January 2, 2006")),
		logLine("Time", in.GeneratedAt.Format("3:04:05 PM")),
		logLine("Generated By", strings.TrimSpace(in.GeneratedBy)),
		"",
		"CLUB",
		strings.Repeat("-", logRule),
		logLine("Club Name", strings.TrimSpace(in.Club.Name)),
		logLine("Club Code", code),
		logLine("LSC Code", lsc),
		logLine("Code (LSC-Club)", clubLabel(lsc, code)),
		logLine("Address", strings.Join(address, ", ")),
		"",
		"MEET",
		strings.Repeat("-", logRule),
		logLine("Meet Name", strings.TrimSpace(in.Meet.Name)),
		logLine("Start Date", in.Meet.Start.Format("January 2, 2006")),
		logLine("End Date", in.Meet.End.Format("January 2, 2006")),
		"",
		"ENTRIES",
		strings.Repeat("-", logRule),
		logLine("Athletes", fmt.Sprintf("%d", len(p.byName))),
		logLine("Individual Entries", fmt.Sprintf("%d", p.individualEntryCount())),
		logLine("Relay Teams", fmt.Sprintf("%d", in.RelayTeams)),
		"",
		"FILES",
		strings.Repeat("-", logRule),
	}
	lines = append(lines, fileNames...)
	return []byte(strings.Join(lines, "\n"))
}

// clubLabel is "LSC-CODE", or just the code when the LSC is unknown.
func clubLabel(lsc, code string) string {
	if lsc == "" {
		return code
	}
	return lsc + "-" + code
}
