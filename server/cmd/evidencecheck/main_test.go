func TestRunAcceptsCompleteEvidenceBundle(t *testing.T) {
	dir := makeBundle(t)

	if err := run([]string{"-dir", dir}); err != nil {
		t.Fatalf("run returned error: %v", err)
	}
}

func TestRunRejectsMigrationComparisonMismatch(t *testing.T) {
	dir := makeBundle(t)
	write(t, filepath.Join(dir, "migration-report.json"), `{
  "errors": [],
  "comparisons": [
    {"name":"row_count_households","status":"mismatch"},
    {"name":"billing_outstanding_total_cents","status":"match"}
  ]
}`)

	err := run([]string{"-dir", dir})
	if err == nil || !strings.Contains(err.Error(), "row_count_households") {
		t.Fatalf("expected comparison failure, got %v", err)
	}
}

func TestRunRejectsSkippedProviderValidation(t *testing.T) {
	dir := makeBundle(t)
	write(t, filepath.Join(dir, "provider-validation-required.md"), "provider skipped")

	err := run([]string{"-dir", dir})
	if err == nil || !strings.Contains(err.Error(), "provider validation was skipped") {
		t.Fatalf("expected skipped provider failure, got %v", err)
	}
}

func makeBundle(t *testing.T) string {
	t.Helper()
	dir := t.TempDir()
	write(t, filepath.Join(dir, "metadata.json"), `{}`)
	write(t, filepath.Join(dir, "manifest.txt"), "manifest")
	write(t, filepath.Join(dir, "migration-dry-run.log"), "dry-run completed successfully")
	write(t, filepath.Join(dir, "cutover-smoke.log"), "PASS health live\nPASS health ready")
	write(t, filepath.Join(dir, "cutover-billing-check.log"), `{"reconciliation":{}}`)
	write(t, filepath.Join(dir, "remediation-log.md"), "No manual remediation items were generated by this dry-run.")
	write(t, filepath.Join(dir, "migration-report.json"), `{
  "errors": [],
  "comparisons": [
    {"name":"row_count_households","status":"match"},
    {"name":"row_count_swimmers","status":"match"},
    {"name":"row_count_groups","status":"match"},
    {"name":"row_count_historical_best_times","status":"match"},
    {"name":"row_count_open_invoices","status":"match"},
    {"name":"row_count_payment_history","status":"match"},
    {"name":"billing_outstanding_total_cents","status":"match"}
  ]
}`)

	provider := filepath.Join(dir, "provider-validation")
	mkdir(t, provider)
	write(t, filepath.Join(provider, "metadata.json"), `{"expect_stripe_webhook_event_id":"evt_launch_1"}`)
	write(t, filepath.Join(provider, "health-ready.json"), `{}`)
	write(t, filepath.Join(provider, "health-ready.json.status"), `200`)
	write(t, filepath.Join(provider, "stripe-reconciliation.json"), `{"reconciliation":{"stripe_reported_cents":12345,"alert_triggered":false}}`)
	write(t, filepath.Join(provider, "stripe-reconciliation.json.status"), `200`)
	write(t, filepath.Join(provider, "stripe-webhook-events.json"), `{"count":1,"events":[{"event_id":"evt_launch_1"}]}`)
	write(t, filepath.Join(provider, "stripe-webhook-events.json.status"), `200`)
	write(t, filepath.Join(provider, "stripe-refund.json"), `{}`)
	write(t, filepath.Join(provider, "stripe-refund.json.status"), `200`)
	write(t, filepath.Join(provider, "postmark-send.json"), `{}`)
	write(t, filepath.Join(provider, "postmark-send.json.status"), `200`)
	write(t, filepath.Join(provider, "postmark-deliveries.json"), `{"count":1,"deliveries":[{"status":"sent","provider_message_id":"postmark-message-1"}]}`)
	write(t, filepath.Join(provider, "postmark-deliveries.json.status"), `200`)
	write(t, filepath.Join(provider, "validation-summary.md"), strings.Join([]string{
		"Expected Stripe webhook event: found",
		"Stripe refund validation: executed",
		"Postmark delivery validation: send_executed",
	}, "\n"))

	parallel := filepath.Join(dir, "parallel-meet-cycles")
	mkdir(t, parallel)
	write(t, filepath.Join(parallel, "cycle-validation-summary.md"), "Result: PASS")

	stability := filepath.Join(dir, "stability-report")
	mkdir(t, stability)
	write(t, filepath.Join(stability, "stability-report.md"), "Result: PASS")

	return dir
}

func TestRunRejectsProviderReconciliationAlert(t *testing.T) {
	dir := makeBundle(t)
	write(t, filepath.Join(dir, "provider-validation", "stripe-reconciliation.json"), `{"reconciliation":{"stripe_reported_cents":12345,"alert_triggered":true}}`)

	err := run([]string{"-dir", dir})
	if err == nil || !strings.Contains(err.Error(), "alert_triggered=true") {
		t.Fatalf("expected reconciliation alert failure, got %v", err)
	}
}

